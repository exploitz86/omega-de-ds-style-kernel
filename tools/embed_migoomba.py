#!/usr/bin/env python3
"""Generate or verify the pinned MiGoomba GBA payload header."""
import argparse
import hashlib
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
METADATA = ROOT / "tools" / "migoomba_payload.json"


def extract_header_payload(header: Path) -> bytes:
    text = header.read_text(encoding="ascii")
    match = re.search(r"migoomba_gba\[(\d+)\].*?=\s*\{(.*?)\};", text, re.S)
    if not match:
        raise SystemExit(f"MiGoomba array is missing from {header}")

    payload = bytes(
        int(value, 16)
        for value in re.findall(r"0x([0-9A-Fa-f]{2})\b", match.group(2))
    )
    if len(payload) != int(match.group(1)):
        raise SystemExit("MiGoomba array initializer does not match its declared size")
    return payload


def validate_payload(payload: bytes, metadata: dict) -> None:
    if len(payload) != metadata["bytes"]:
        raise SystemExit(f"Expected {metadata['bytes']} payload bytes, found {len(payload)}")
    if hashlib.sha256(payload).hexdigest() != metadata["sha256"]:
        raise SystemExit("Payload SHA-256 does not match the pinned MiGoomba build")
    if not 0xC0 <= len(payload) <= 0x20000 or len(payload) % 4:
        raise SystemExit("Payload must fit the 128 KiB loader cache and be word-aligned")
    if payload[0xAC:0xB0] != b"GMBC" or payload[0xB2] != 0x96:
        raise SystemExit("Payload is not the expected Goomba-compatible GBA image")
    checksum = (-sum(payload[0xA0:0xBD]) - 0x19) & 0xFF
    if payload[0xBD] != checksum:
        raise SystemExit("Payload has an invalid GBA header checksum")


def render_header(payload: bytes, metadata: dict) -> str:
    rows = [
        "\t" + ", ".join(f"0x{byte:02X}" for byte in payload[offset : offset + 16]) + ","
        for offset in range(0, len(payload), 16)
    ]
    return (
        "/* Generated by tools/embed_migoomba.py; do not edit. */\n"
        f"/* MiGoomba {metadata['version']}, {metadata['variant']}; "
        f"upstream {metadata['upstream_commit']}. */\n"
        f"const unsigned int migoomba_gba_size = {len(payload)};\n"
        f"const unsigned char migoomba_gba[{len(payload)}] "
        "__attribute__((aligned(4))) = {\n"
        + "\n".join(rows)
        + "\n};\n"
    )


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("binary", nargs="?", type=Path, help="MiGoomba ezode GBA binary")
    parser.add_argument("--check", action="store_true", help="verify the committed header")
    args = parser.parse_args()
    if not args.binary and not args.check:
        parser.error("Provide the upstream GBA binary, or use --check")

    metadata = json.loads(METADATA.read_text(encoding="utf-8"))
    header = ROOT / metadata["embedded_header"]
    payload = args.binary.read_bytes() if args.binary else extract_header_payload(header)
    validate_payload(payload, metadata)
    generated = render_header(payload, metadata)

    if args.check:
        if not header.exists() or header.read_text(encoding="ascii") != generated:
            raise SystemExit("Embedded header differs from deterministic generator output")
        print(
            f"MiGoomba {metadata['variant']}: {len(payload)} bytes, "
            "hash/header/alignment verified."
        )
    else:
        header.write_text(generated, encoding="ascii", newline="\n")
        print(f"Wrote {header.relative_to(ROOT)} ({len(payload)} bytes).")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
